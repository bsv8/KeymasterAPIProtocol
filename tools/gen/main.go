// Command gen 从 openapi/openapi.yaml 的 components.schemas 派生 Go 与 TS 类型。
// 只支持本仓使用到的 OpenAPI 子集：object/array/string/integer/number/
// boolean、$ref、enum、required、format。输出禁止手工修改。
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type Schema struct {
	Type        string             `yaml:"type"`
	Format      string             `yaml:"format"`
	Ref         string             `yaml:"$ref"`
	Items       *Schema            `yaml:"items"`
	Properties  map[string]*Schema `yaml:"properties"`
	Required    []string           `yaml:"required"`
	Enum        []any              `yaml:"enum"`
	Description string             `yaml:"description"`
}

type Spec struct {
	Components struct {
		Schemas map[string]*Schema `yaml:"schemas"`
	} `yaml:"components"`
}

func goName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	out := b.String()
	out = strings.ReplaceAll(out, "Id", "ID")
	out = strings.ReplaceAll(out, "Api", "API")
	out = strings.ReplaceAll(out, "Url", "URL")
	return out
}

func goField(name string) string {
	if name == "id" {
		return "ID"
	}
	return goName(name)
}

func tsName(name string) string { return name }

func refBase(ref string) string {
	i := strings.LastIndex(ref, "/")
	if i < 0 {
		return ref
	}
	return ref[i+1:]
}

func goType(s *Schema, optional bool) string {
	if s == nil {
		return "any"
	}
	if s.Ref != "" {
		t := goName(refBase(s.Ref))
		if optional {
			return "*" + t
		}
		return t
	}
	switch s.Type {
	case "string":
		if optional {
			return "*string"
		}
		return "string"
	case "integer":
		switch s.Format {
		case "int64":
			if optional {
				return "*int64"
			}
			return "int64"
		case "uint64":
			if optional {
				return "*uint64"
			}
			return "uint64"
		default:
			if optional {
				return "*int"
			}
			return "int"
		}
	case "number":
		if optional {
			return "*float64"
		}
		return "float64"
	case "boolean":
		if optional {
			return "*bool"
		}
		return "bool"
	case "array":
		return "[]" + goType(s.Items, false)
	case "object":
		return "map[string]any"
	default:
		return "any"
	}
}

func tsType(s *Schema) string {
	if s == nil {
		return "unknown"
	}
	if s.Ref != "" {
		return goName(refBase(s.Ref))
	}
	switch s.Type {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return tsType(s.Items) + "[]"
	case "object":
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "用法: gen <openapi.yaml> <types.gen.go> <types.gen.ts>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var spec Spec
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(spec.Components.Schemas))
	for n := range spec.Components.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)

	var goOut strings.Builder
	goOut.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	goOut.WriteString("// 来源: openapi/openapi.yaml components.schemas。\npackage kmapi\n\n")
	for _, n := range names {
		s := spec.Components.Schemas[n]
		if s.Type != "object" {
			continue
		}
		req := map[string]bool{}
		for _, r := range s.Required {
			req[r] = true
		}
		props := make([]string, 0, len(s.Properties))
		for p := range s.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		goOut.WriteString("type " + goName(n) + " struct {\n")
		for _, p := range props {
			ps := s.Properties[p]
			optional := !req[p]
			jt := p
			if optional {
				jt += ",omitempty"
			}
			// 可选引用保持指针以区分“未提供”；可选数组/字典本身
			// 已可空（nil），无需指针。
			ptr := optional && (ps.Ref != "" || (ps.Type != "array" && ps.Type != "object"))
			goOut.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goField(p), goType(ps, ptr), jt))
		}
		goOut.WriteString("}\n\n")
	}

	var tsOut strings.Builder
	tsOut.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	tsOut.WriteString("// 来源: openapi/openapi.yaml components.schemas。\n\n")
	for _, n := range names {
		s := spec.Components.Schemas[n]
		if s.Type != "object" {
			continue
		}
		req := map[string]bool{}
		for _, r := range s.Required {
			req[r] = true
		}
		props := make([]string, 0, len(s.Properties))
		for p := range s.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		tsOut.WriteString("export interface " + goName(n) + " {\n")
		for _, p := range props {
			ps := s.Properties[p]
			opt := ""
			if !req[p] {
				opt = "?"
			}
			t := tsType(ps)
			if !req[p] && t != "unknown" && !strings.HasSuffix(t, "[]") && !strings.HasPrefix(t, "Record") && !strings.HasPrefix(t, "unknown") {
				// 可选标量在 TS 中直接可选，不用指针。
			}
			tsOut.WriteString(fmt.Sprintf("  %s%s: %s;\n", tsName(p), opt, t))
		}
		tsOut.WriteString("}\n\n")
	}

	if err := os.MkdirAll(filepath.Dir(os.Args[2]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(os.Args[3]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	formatted, err := format.Source([]byte(goOut.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt: "+err.Error())
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[3], []byte(tsOut.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
