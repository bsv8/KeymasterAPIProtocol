// Command gen 从 spec/protocol.yaml 派生 Go 与 TS 类型、方法映射与协议常量。
// 只支持本仓使用到的子集：object/array/string/integer/number/
// boolean、$ref、enum、required、format。输出禁止手工修改。
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type Schema struct {
	Type        string             `yaml:"type"`
	Format      string             `yaml:"format"`
	Ref         string             `yaml:"$ref"`
	Items       *Schema            `yaml:"items"`
	Properties  map[string]*Schema `yaml:"properties"`
	Required    []string           `yaml:"required"`
	Enum        []any              `yaml:"enum"`
	Description string             `yaml:"description"`
}

type MethodSpec struct {
	Name        string `yaml:"name"`
	Params      string `yaml:"params"`
	Result      string `yaml:"result"`
	Timeout     string `yaml:"timeout"`
	Description string `yaml:"description"`
}

type ErrorSpec struct {
	Code        string `yaml:"code"`
	Description string `yaml:"description"`
}

type Spec struct {
	Info struct {
		Product    string `yaml:"product"`
		APIVersion string `yaml:"apiVersion"`
		WSPath     string `yaml:"wsPath"`
	} `yaml:"info"`
	Limits map[string]any `yaml:"limits"`
	Topics []string       `yaml:"topics"`
	Methods []MethodSpec  `yaml:"methods"`
	Errors  []ErrorSpec   `yaml:"errors"`
	Schemas map[string]*Schema `yaml:"schemas"`
}

func goName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	out := b.String()
	out = strings.ReplaceAll(out, "Id", "ID")
	out = strings.ReplaceAll(out, "Api", "API")
	out = strings.ReplaceAll(out, "Url", "URL")
	return out
}

func goField(name string) string {
	if name == "id" {
		return "ID"
	}
	return goName(name)
}

func tsName(name string) string { return name }

func methodConst(name string) string {
	// "status.get" -> "MethodStatusGet"
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '.' || r == '_' || r == '-' })
	var b strings.Builder
	b.WriteString("Method")
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func goType(s *Schema, optional bool) string {
	if s == nil {
		return "any"
	}
	if s.Ref != "" {
		t := goName(refBase(s.Ref))
		if optional {
			return "*" + t
		}
		return t
	}
	switch s.Type {
	case "string":
		if optional {
			return "*string"
		}
		return "string"
	case "integer":
		switch s.Format {
		case "int64":
			if optional {
				return "*int64"
			}
			return "int64"
		case "uint64":
			if optional {
				return "*uint64"
			}
			return "uint64"
		default:
			if optional {
				return "*int"
			}
			return "int"
		}
	case "number":
		if optional {
			return "*float64"
		}
		return "float64"
	case "boolean":
		if optional {
			return "*bool"
		}
		return "bool"
	case "array":
		return "[]" + goType(s.Items, false)
	case "object":
		return "map[string]any"
	default:
		return "any"
	}
}

func tsType(s *Schema) string {
	if s == nil {
		return "unknown"
	}
	if s.Ref != "" {
		return goName(refBase(s.Ref))
	}
	switch s.Type {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		return tsType(s.Items) + "[]"
	case "object":
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func refBase(ref string) string {
	i := strings.LastIndex(ref, "/")
	if i < 0 {
		return ref
	}
	return ref[i+1:]
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "用法: gen <spec/protocol.yaml> <kmapi/types.gen.go> <typescript/src/types.gen.ts>")
		fmt.Fprintln(os.Stderr, "同时生成同目录 methods.gen.go / methods.gen.ts")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var spec Spec
	if err := yaml.Unmarshal(raw, &spec); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(spec.Schemas))
	for n := range spec.Schemas {
		names = append(names, n)
	}
	sort.Strings(names)

	var goOut strings.Builder
	goOut.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	goOut.WriteString("// 来源: spec/protocol.yaml schemas。\npackage kmapi\n\n")
	for _, n := range names {
		s := spec.Schemas[n]
		if s.Type != "object" {
			continue
		}
		req := map[string]bool{}
		for _, r := range s.Required {
			req[r] = true
		}
		props := make([]string, 0, len(s.Properties))
		for p := range s.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		goOut.WriteString("type " + goName(n) + " struct {\n")
		for _, p := range props {
			ps := s.Properties[p]
			optional := !req[p]
			jt := p
			if optional {
				jt += ",omitempty"
			}
			ptr := optional && (ps.Ref != "" || (ps.Type != "array" && ps.Type != "object"))
			goOut.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goField(p), goType(ps, ptr), jt))
		}
		goOut.WriteString("}\n\n")
	}

	var tsOut strings.Builder
	tsOut.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	tsOut.WriteString("// 来源: spec/protocol.yaml schemas。\n\n")
	for _, n := range names {
		s := spec.Schemas[n]
		if s.Type != "object" {
			continue
		}
		req := map[string]bool{}
		for _, r := range s.Required {
			req[r] = true
		}
		props := make([]string, 0, len(s.Properties))
		for p := range s.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		tsOut.WriteString("export interface " + goName(n) + " {\n")
		for _, p := range props {
			ps := s.Properties[p]
			opt := ""
			if !req[p] {
				opt = "?"
			}
			t := tsType(ps)
			tsOut.WriteString(fmt.Sprintf("  %s%s: %s;\n", tsName(p), opt, t))
		}
		tsOut.WriteString("}\n\n")
	}

	// 方法与协议常量
	methods := append([]MethodSpec(nil), spec.Methods...)
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name < methods[j].Name })
	errs := append([]ErrorSpec(nil), spec.Errors...)
	sort.Slice(errs, func(i, j int) bool { return errs[i].Code < errs[j].Code })
	topics := append([]string(nil), spec.Topics...)
	sort.Strings(topics)

	var goMethods strings.Builder
	goMethods.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	goMethods.WriteString("// 来源: spec/protocol.yaml methods/errors/topics/info。\npackage kmapi\n\n")
	goMethods.WriteString(fmt.Sprintf("const Product = %q\nconst APIVersion = %q\nconst WSPath = %q\n\n", spec.Info.Product, spec.Info.APIVersion, spec.Info.WSPath))
	goMethods.WriteString("const (\n")
	for _, m := range methods {
		params := m.Params
		if params == "" || params == "null" {
			params = "nil"
		}
		result := m.Result
		if result == "" || result == "null" {
			result = "nil"
		}
		goMethods.WriteString(fmt.Sprintf("\t%s = %q // params=%s result=%s timeout=%s\n", methodConst(m.Name), m.Name, params, result, m.Timeout))
	}
	goMethods.WriteString(")\n\n")
	goMethods.WriteString("// MethodTimeout 将方法映射到超时类别：probe/short/long/stream/connect。\n")
	goMethods.WriteString("var MethodTimeout = map[string]string{\n")
	for _, m := range methods {
		goMethods.WriteString(fmt.Sprintf("\t%q: %q,\n", m.Name, m.Timeout))
	}
	goMethods.WriteString("}\n\n")
	goMethods.WriteString("// MethodParams 将方法映射到参数类型名（null 表示无参数）。\n")
	goMethods.WriteString("var MethodParams = map[string]string{\n")
	for _, m := range methods {
		p := m.Params
		if p == "" {
			p = "null"
		}
		goMethods.WriteString(fmt.Sprintf("\t%q: %q,\n", m.Name, p))
	}
	goMethods.WriteString("}\n\n")
	goMethods.WriteString("// MethodResult 将方法映射到结果类型名。\n")
	goMethods.WriteString("var MethodResult = map[string]string{\n")
	for _, m := range methods {
		r := m.Result
		if r == "" {
			r = "null"
		}
		goMethods.WriteString(fmt.Sprintf("\t%q: %q,\n", m.Name, r))
	}
	goMethods.WriteString("}\n\n")
	goMethods.WriteString("const (\n")
	for _, e := range errs {
		goMethods.WriteString(fmt.Sprintf("\tErr%s = %q\n", goName(strings.ToLower(e.Code)), e.Code))
	}
	goMethods.WriteString(")\n\n")
	goMethods.WriteString("var KnownTopics = []string{\n")
	for _, t := range topics {
		goMethods.WriteString(fmt.Sprintf("\t%q,\n", t))
	}
	goMethods.WriteString("}\n")

	var tsMethods strings.Builder
	tsMethods.WriteString("// Code generated by tools/gen. DO NOT EDIT.\n")
	tsMethods.WriteString("// 来源: spec/protocol.yaml methods/errors/topics/info。\n\n")
	tsMethods.WriteString(fmt.Sprintf("export const Product = %q;\nexport const APIVersion = %q;\nexport const WSPath = %q;\n\n", spec.Info.Product, spec.Info.APIVersion, spec.Info.WSPath))
	for _, m := range methods {
		tsMethods.WriteString(fmt.Sprintf("export const %s = %q; // params=%s result=%s timeout=%s\n", methodConst(m.Name), m.Name, orNull(m.Params), orNull(m.Result), m.Timeout))
	}
	tsMethods.WriteString("\nexport const MethodTimeout: Record<string, string> = {\n")
	for _, m := range methods {
		tsMethods.WriteString(fmt.Sprintf("  %q: %q,\n", m.Name, m.Timeout))
	}
	tsMethods.WriteString("};\n\nexport const MethodParams: Record<string, string> = {\n")
	for _, m := range methods {
		tsMethods.WriteString(fmt.Sprintf("  %q: %q,\n", m.Name, orNull(m.Params)))
	}
	tsMethods.WriteString("};\n\nexport const MethodResult: Record<string, string> = {\n")
	for _, m := range methods {
		tsMethods.WriteString(fmt.Sprintf("  %q: %q,\n", m.Name, orNull(m.Result)))
	}
	tsMethods.WriteString("};\n\nexport const ErrorCodes = [\n")
	for _, e := range errs {
		tsMethods.WriteString(fmt.Sprintf("  %q,\n", e.Code))
	}
	tsMethods.WriteString("] as const;\nexport type ErrorCode = typeof ErrorCodes[number];\n\nexport const KnownTopics = [\n")
	for _, t := range topics {
		tsMethods.WriteString(fmt.Sprintf("  %q,\n", t))
	}
	tsMethods.WriteString("] as const;\n")

	if err := os.MkdirAll(filepath.Dir(os.Args[2]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(os.Args[3]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	formatted, err := format.Source([]byte(goOut.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt types: "+err.Error())
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], formatted, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[3], []byte(tsOut.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// 同目录 methods.gen
	goMethodsPath := filepath.Join(filepath.Dir(os.Args[2]), "methods.gen.go")
	tsMethodsPath := filepath.Join(filepath.Dir(os.Args[3]), "methods.gen.ts")
	formattedMethods, err := format.Source([]byte(goMethods.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt methods: "+err.Error())
		os.Exit(1)
	}
	if err := os.WriteFile(goMethodsPath, formattedMethods, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(tsMethodsPath, []byte(tsMethods.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func orNull(s string) string {
	if s == "" {
		return "null"
	}
	return s
}
